//! Generates the registry of ported document checks.
//!
//! Every file `src/doccheck/checks/c<id>.rs` (or directory
//! `src/doccheck/checks/c<id>/mod.rs`) is one ported check and must define
//! `pub const SPEC: CheckSpec`. The registry is generated from the directory
//! listing so that porters working in parallel never edit a shared file.

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let dir = Path::new(&env::var("CARGO_MANIFEST_DIR").expect("cargo sets it"))
        .join("src")
        .join("doccheck")
        .join("checks");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut mods: Vec<(String, String)> = Vec::new();
    for entry in fs::read_dir(&dir)
        .expect("src/doccheck/checks exists")
        .flatten()
    {
        let path = entry.path();
        let name = entry.file_name().to_string_lossy().into_owned();
        if !name.starts_with('c') || !name[1..].starts_with(|c: char| c.is_ascii_digit()) {
            continue;
        }
        let (module, file) = if path.is_dir() {
            (name.clone(), path.join("mod.rs"))
        } else if let Some(stem) = name.strip_suffix(".rs") {
            (stem.to_string(), path.clone())
        } else {
            continue;
        };
        if file.is_file() {
            println!("cargo:rerun-if-changed={}", file.display());
            mods.push((module, file.display().to_string()));
        }
    }
    mods.sort();
    let mut out = String::from("// Generated by build.rs from src/doccheck/checks/.\n");
    for (module, file) in &mods {
        out.push_str(&format!("#[path = {file:?}]\npub mod {module};\n"));
    }
    out.push_str("\n/// Every ported check, sorted by id.\npub fn registry() -> Vec<&'static CheckSpec> {\n    vec![");
    for (module, _) in &mods {
        out.push_str(&format!("&{module}::SPEC, "));
    }
    out.push_str("]\n}\n");
    let dest = Path::new(&env::var("OUT_DIR").expect("cargo sets it")).join("checks_registry.rs");
    fs::write(dest, out).expect("OUT_DIR is writable");
}
